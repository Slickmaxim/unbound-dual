#!/usr/bin/env python3
"""Generates source/ui_font.c: anti-aliased 4-bit glyph atlases (ASCII 32..126,
Latin-1 160..255, then the Russian alphabet and №)
from the Inter typeface (SIL Open Font License 1.1, https://rsms.me/inter/).
usage: make_font.py <font dir> <out.c> [companion cyrillic.inc]"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [  # name, file, pixel size
    ("ui_font_small", "Inter-Medium.otf", 11),
    ("ui_font_body",  "Inter-Medium.otf", 14),
    ("ui_font_bold",  "Inter-SemiBold.otf", 15),
    ("ui_font_title", "InterDisplay-Bold.otf", 19),
    ("ui_font_big",   "InterDisplay-Bold.otf", 30),
]

CYRILLIC = [0x401, *range(0x410, 0x450), 0x451, 0x2116]
CHARACTERS = [*range(32, 127), *range(160, 256), *CYRILLIC]
fdir, out = sys.argv[1], sys.argv[2]
o = ['/* Generated by tools/make_font.py from Inter (SIL OFL 1.1). Do not edit. */',
     '#include "ui.h"', '']
for name, fname, size in FONTS:
    font = ImageFont.truetype(f"{fdir}/{fname}", size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for c in CHARACTERS:
        ch = chr(c)
        adv = round(font.getlength(ch))
        bbox = font.getbbox(ch)  # relative to the top of the ascent line
        x0, y0, x1, y1 = bbox
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
            px = list(img.getdata())
            nib = [min(15, (v + 8) // 17) for v in px]
            if len(nib) & 1:
                nib.append(0)
            for i in range(0, len(nib), 2):
                data.append(nib[i] | (nib[i + 1] << 4))
        glyphs.append((x0, y0, w, h, adv, off))
    o.append(f"static const unsigned char {name}_bits[{max(1,len(data))}] = {{")
    for i in range(0, len(data), 24):
        o.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    if not data:
        o.append("  0")
    o.append("};")
    o.append(f"static const ui_glyph {name}_glyphs[{len(CHARACTERS)}] = {{")
    for g in glyphs:
        o.append("  {%d,%d,%d,%d,%d,%d}," % g)
    o.append("};")
    o.append(f"const ui_font {name} = {{ {ascent + descent}, {ascent}, {name}_glyphs, {name}_bits }};")
    o.append("")
open(out, "w").write("\n".join(o))
print("wrote", out)

if len(sys.argv) > 3:
    # Match the companion's 16-row font and baseline (row 13).
    # Threshold the Inter glyphs for the existing 1-bit renderer.
    font = ImageFont.truetype(f"{fdir}/Inter-Medium.otf", 11)
    ascent, _ = font.getmetrics()
    with open(sys.argv[3], "w", encoding="utf-8") as companion:
        companion.write("// Generated by tools/make_font.py from Inter (SIL OFL 1.1).\n")
        for c in CYRILLIC:
            ch = chr(c)
            x0, _, x1, _ = font.getbbox(ch)
            left = min(0, x0)
            advance = max(round(font.getlength(ch)), x1) - left
            img = Image.new("L", (16, 16))
            ImageDraw.Draw(img).text((-left, 13 - ascent), ch, font=font, fill=255)
            rows = [sum((img.getpixel((x, y)) >= 100) << x for x in range(16)) for y in range(16)]
            masks = ", ".join(f"0x{row:04X}" for row in rows)
            companion.write(f"    {{ 0x{c:04X}, {advance}, {{ {masks} }}, 0 }}, // {ch}\n")
