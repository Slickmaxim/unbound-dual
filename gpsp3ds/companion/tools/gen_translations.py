#!/usr/bin/env python3
"""Generate the sorted, allocation-free interface translation table."""
import json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
d=json.loads((root/'i18n/es.json').read_text())
fmt=re.compile(r'%(?:\d+\$)?[-+#0]*[\d*]*(?:\.[\d*]+)?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcspn%]')
for a,b in d.items():
 if fmt.findall(a)!=fmt.findall(b):raise ValueError('printf argument mismatch: '+a)
q=lambda s:json.dumps(s,ensure_ascii=False)
(root/'translations_es.inc').write_text('// Generated by tools/gen_translations.py from i18n/es.json.\nstatic const struct translation translations[] = {\n'+''.join(' {'+q(k)+','+q(v)+'},\n' for k,v in sorted(d.items()))+'};\n')
print(len(d),'translation keys; printf argument order checked')
