#!/usr/bin/env python3
"""Generate the sorted, allocation-free interface translation tables."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
fmt = re.compile(r'%(?:\d+\$)?[-+#0]*[\d*]*(?:\.[\d*]+)?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcspn%]')

def quote(text):
    return json.dumps(text, ensure_ascii=False)

for source in sorted((root / 'i18n').glob('*.json')):
    code = source.stem
    table = json.loads(source.read_text())
    for english, translated in table.items():
        if fmt.findall(english) != fmt.findall(translated):
            raise ValueError(f'{code}: printf argument mismatch: {english!r} -> {translated!r}')
    rows = ''.join(f' {{{quote(k)},{quote(v)}}},\n' for k, v in sorted(table.items()))
    (root / f'translations_{code}.inc').write_text(
        f'// Generated by tools/gen_translations.py from i18n/{code}.json.\n'
        f'static const struct translation translations_{code}[] = {{\n{rows}}};\n'
    )
    print(f'{code}: {len(table)} keys; printf argument order checked')
